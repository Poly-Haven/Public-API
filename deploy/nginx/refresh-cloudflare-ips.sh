#!/usr/bin/env bash
# Writes nginx's list of Cloudflare's address ranges (the `set_real_ip_from` lines that api.polyhaven.com.conf includes).
#   refresh-cloudflare-ips.sh [dest]        dest defaults to /etc/nginx/cloudflare-ips.conf
# Fetches https://www.cloudflare.com/ips-v4 and /ips-v6. If either fetch fails or returns something that is not a
# plausible list of CIDR ranges, falls back to the copy checked in next to this script (cloudflare-ips.conf), so a
# provision never fails, or ends up with an empty list, because Cloudflare's site was unreachable. Run by
# provision.sh; run it again (then `nginx -t && systemctl reload nginx`) when Cloudflare announces new ranges.
# To refresh the checked-in copy: refresh-cloudflare-ips.sh deploy/nginx/cloudflare-ips.conf, then commit.
set -euo pipefail

DEST="${1:-/etc/nginx/cloudflare-ips.conf}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FALLBACK="$HERE/cloudflare-ips.conf"
out="$(mktemp)"
trap 'rm -f "$out"' EXIT

# One CIDR per line, nothing else (the v4 list has no trailing newline, hence awk rather than read).
fetch() { curl -fsS --max-time 20 "$1" | tr -d '\r' | awk 'NF'; }
all_cidrs() { ! grep -qvE '^[0-9a-fA-F:.]+/[0-9]{1,3}$' <<<"$1"; }

if v4="$(fetch https://www.cloudflare.com/ips-v4)" && v6="$(fetch https://www.cloudflare.com/ips-v6)" \
  && all_cidrs "$v4" && all_cidrs "$v6" && [ "$(wc -l <<<"$v4")" -ge 5 ] && [ "$(wc -l <<<"$v6")" -ge 3 ]; then
  {
    echo "# Cloudflare's address ranges, fetched $(date -u +%Y-%m-%d) from https://www.cloudflare.com/ips-v4 and /ips-v6."
    echo "# Generated by deploy/nginx/refresh-cloudflare-ips.sh; do not edit by hand."
    sed 's/.*/set_real_ip_from &;/' <<<"$v4"
    sed 's/.*/set_real_ip_from &;/' <<<"$v6"
  } > "$out"
  echo "cloudflare ranges: fetched ($(wc -l <<<"$v4") IPv4, $(wc -l <<<"$v6") IPv6)"
else
  [ -f "$FALLBACK" ] || { echo "could not fetch Cloudflare's ranges and there is no checked-in copy at $FALLBACK" >&2; exit 1; }
  echo "WARNING: could not fetch Cloudflare's ranges; using the checked-in copy ($FALLBACK)" >&2
  cp "$FALLBACK" "$out"
fi

# Atomic, so nginx never reads a half-written file.
install -m 644 "$out" "$DEST"
